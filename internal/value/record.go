package value

// Запись — ОТКРЫТАЯ структура с сохранением порядка полей (§2.1, D5). Хранит
// keys []string (порядок появления — важен для печати §7) + fields map (доступ
// за O(1)). Ссылочная (map). В чистом 003 НЕ конструируется (нет литерала,
// источники — доменные функции deferred), но смоделирована полностью: чтение
// полей, равенство (equal.go), печать (repr.go). FieldExpr в 003 всегда упирается
// в «значение типа <тип> не имеет полей» (D5) — механизм чтения готов к моменту,
// когда engine-трек начнёт порождать записи.
type Запись struct {
	keys   []string
	fields map[string]Value
}

func (Запись) TypeName() string { return "Запись" }

// NewRecord строит Запись из упорядоченных ключей и значений. keys задаёт порядок
// печати; значения берутся из fields. Используется будущим store/доменом и
// тестами модели (в чистом 003 ни один путь eval её не вызывает).
func NewRecord(keys []string, fields map[string]Value) Запись {
	return Запись{keys: keys, fields: fields}
}

// Get возвращает значение поля; отсутствующее поле → None (открытая запись,
// не ошибка).
func (r Запись) Get(name string) Value {
	if v, ok := r.fields[name]; ok {
		return v
	}
	return None
}

// Keys возвращает имена полей в порядке появления (для строка()/печать()).
func (r Запись) Keys() []string { return r.keys }
