package value

import "testing"

// Запись смоделирована полностью: читается (Get), печатается в порядке полей,
// сравнивается структурно. В 003 не конструируется eval, но модель обязана
// работать (D5, C-7).
func TestRecordReadPrintEqual(t *testing.T) {
	r := NewRecord(
		[]string{"номер", "сумма"},
		map[string]Value{"номер": Целое{V: 7}, "сумма": Целое{V: 1000}},
	)

	// чтение
	if !Equal(r.Get("номер"), Целое{V: 7}) {
		t.Errorf("Get(номер) = %v", r.Get("номер"))
	}
	// отсутствующее поле → None (открытая запись)
	if !Equal(r.Get("нет"), None) {
		t.Errorf("Get(нет) = %v, хотим пусто", r.Get("нет"))
	}
	// печать в порядке полей
	if got := String(r); got != "{номер: 7, сумма: 1000}" {
		t.Errorf("String = %q", got)
	}
	// структурное равенство (порядок ключей не важен)
	r2 := NewRecord(
		[]string{"сумма", "номер"},
		map[string]Value{"сумма": Целое{V: 1000}, "номер": Целое{V: 7}},
	)
	if !Equal(r, r2) {
		t.Errorf("структурно равные записи не равны")
	}
	// разные значения → не равны
	r3 := NewRecord([]string{"номер"}, map[string]Value{"номер": Целое{V: 8}})
	if Equal(r, r3) {
		t.Errorf("записи с разным набором/значениями равны")
	}
}
