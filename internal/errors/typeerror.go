package errors

import "fmt"

// ОшибкаТипа — ошибка стадии 4 (исполнение): несовместимые операнды бинарных/
// унарных операций, условие не Булево, «для» не над Список, индекс/поле неверного
// типа, ошибки преобразования стдлиб.
//
// Тот же дом-паттерн, что у LexError/ParseError/СемантическаяОшибка: {Pos, Msg} +
// метод-значение Error(). Полезная нагрузка — ДОСЛОВНО из §8.3. Листовость
// сохраняется (НЕ импортирует ast/value).
type ОшибкаТипа struct {
	Pos Position
	Msg string
}

// Error возвращает канонический двухстрочный вид (§8.1).
func (e ОшибкаТипа) Error() string {
	return fmt.Sprintf("Ошибка в строке %d, колонка %d:\n%s", e.Pos.Line, e.Pos.Col, e.Msg)
}

// Позиция реализует Расположенная: ошибка уже несёт позицию (§13).
func (e ОшибкаТипа) Позиция() Position { return e.Pos }
