package errors

import "fmt"

// ParseError — синтаксическая ошибка: позиция проблемного токена (в рунах) плюс
// русское описание БЕЗ заголовка (например "вложенные функции не поддерживаются
// в v1"). Тексты — из contracts/syntax-errors.md; шаблонизация живёт в пакете
// parser, здесь только тип и канонический формат.
//
// Категория Синтаксическая (SPEC §13.1) использует тот же двухстрочный заголовок,
// что и Лексическая (LexError) — различие категорий по слою-источнику, не по
// формату. Складывается в тот же errors.ErrorList (Add(error)/Unwrap() уже
// полиморфны — aggregate.go не меняется, guardrail 8). В штатных путях паника
// запрещена (конституция III).
type ParseError struct {
	Pos Position
	Msg string
}

// Error возвращает канонический двухстрочный вид (SPEC §13), идентичный LexError:
//
//	Ошибка в строке N, колонка M:
//	<описание>
//
// Значение реализует error и разворачивается через errors.As (FR-023).
func (e ParseError) Error() string {
	return fmt.Sprintf("Ошибка в строке %d, колонка %d:\n%s", e.Pos.Line, e.Pos.Col, e.Msg)
}
