package errors

import "fmt"

// СемантическаяОшибка — ошибка стадии 3 (семантический проход Analyze): повтор
// объявления, фиксированная арность, контекст вернуть/прервать/продолжить,
// необъявленная функция, deferred-конструкции и deferred-встроенные.
//
// По образцу LexError/ParseError: листовой тип {Pos, Msg} с методом-ЗНАЧЕНИЕМ
// Error() (важно для errors.As по значению). Полезная нагрузка Msg — ДОСЛОВНО из
// docs/eval-model.md §8.3 (без заголовка); шаблонизация живёт в пакете eval, здесь
// только тип и канонический двухстрочный формат. Тип НЕ импортирует ast/value
// (листовость, Guardrail 14): <тип> подставляет вызывающий eval.
type СемантическаяОшибка struct {
	Pos Position
	Msg string
}

// Error возвращает канонический двухстрочный вид (§8.1), идентичный LexError/
// ParseError:
//
//	Ошибка в строке N, колонка M:
//	<описание>
func (e СемантическаяОшибка) Error() string {
	return fmt.Sprintf("Ошибка в строке %d, колонка %d:\n%s", e.Pos.Line, e.Pos.Col, e.Msg)
}

// Позиция реализует Расположенная: ошибка уже несёт позицию (§13).
func (e СемантическаяОшибка) Позиция() Position { return e.Pos }
