// Package eval — tree-walking интерпретатор чистого императивного ядра Ladix
// (подмножество B, фича 003).
//
// Потребляет AST от парсера (002) как стабильный вход и исполняет программу:
// вычисляет выражения по уже построенному дереву приоритетов (не переразбирает),
// исполняет statements, ведёт ФУНКЦИОНАЛЬНЫЕ области видимости (блоки область не
// открывают), вызывает пользовательские функции с рекурсией и явным счётчиком
// глубины, печатает через печать и сообщает рантайм-/семантические ошибки с
// позицией (строка + колонка в рунах) по-русски.
//
// Граф зависимостей: eval → ast, value, errors (НЕ store/engine в 003). Control-
// flow (вернуть/прервать/продолжить) реализован ЯВНЫМ сигналом Signal, а не
// panic/recover (D4, конституция III); рантайм-ошибки — отдельный канал error,
// fail-fast до границы CLI. Стадия 3 — лёгкий Analyze (резолв имён функций, фикс.
// арность, scope-гарды, deferred-граница); стадия 4 — исполнение.
