// Package ir описывает промежуточное представление (IR) программы LADIX —
// версионируемый контракт вывода компилятора.
//
// Вместе с корневым пакетом ladix это ЕДИНСТВЕННАЯ публичная поверхность модуля
// github.com/denis-kosyakov/ladix. Всё остальное (лексер, парсер, AST, значения,
// ошибки, интерпретатор, движок процессов, хранилище, демон) живёт под internal/
// и частью semver-контракта НЕ является.
//
// # Как получить Program
//
// Только через фасад: ladix.Compile(source) или ladix.CompileFile(path).
// Собирать Program вручную не требуется — типы экспортированы для чтения,
// сериализации и передачи между сервисами.
//
// # Версионирование (SchemaVersion)
//
// BREAKING (требует bump SchemaVersion): удаление или переименование поля, смена
// типа поля, смена семантики существующего поля, смена формата канонических
// строк выражений (в частности будущий переход выражений из строк в структурное
// представление — это будет v2).
//
// АДДИТИВНО (SchemaVersion НЕ меняется): добавление нового опционального поля,
// появление нового значения Severity (например warning) или Stage.
//
// # Требование к потребителю (forward-compat)
//
// Потребитель IR ОБЯЗАН быть толерантным:
//
//   - неизвестное JSON-поле — игнорировать, не падать;
//   - неизвестное значение Severity — трактовать как не менее чем информативное,
//     не падать (не предполагать закрытый словарь);
//   - неизвестное значение Stage — игнорировать смысл этапа, не падать.
//
// Без этой толерантности любое аддитивное расширение станет для потребителя
// breaking-изменением, чего политика версионирования не предполагает.
//
// # JSON
//
// Все поля несут snake_case-теги; omitempty НЕ используется — незаданные строки
// сериализуются как "", а не опускаются, поэтому форма объекта стабильна.
