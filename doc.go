// Package ladix — публичная точка входа библиотеки LADIX: компиляция исходника
// бизнес-определений (метрики, процессы, триггеры) в стабильное промежуточное
// представление [ir.Program].
//
// LADIX — декларативно-императивный DSL для системы управления бизнесом «Уклад».
// Эта библиотека даёт внешним системам ФРОНТЕНД языка (разбор + валидация +
// нормализация), чтобы исполнять определения нативно, своим движком.
//
// # Публичная поверхность
//
// Модуль экспортирует РОВНО два пакета: этот (Compile / CompileFile) и
// [github.com/denis-kosyakov/ladix/ir] (типы результата). Лексер, парсер, AST,
// значения, ошибки, интерпретатор, движок процессов, хранилище и демон живут
// под internal/ и частью semver-контракта НЕ являются — они могут меняться в
// любом релизе. Отдельно поставляется reference-CLI cmd/ladix, исполняющий
// программы целиком; библиотеке он не нужен.
//
// # Пример
//
//	program, diags, err := ladix.Compile(source)
//	if err != nil {
//	    return err // внутренний сбой
//	}
//	if program == nil {
//	    for _, d := range diags {
//	        fmt.Printf("%s:%d:%d %s\n", d.Stage, d.Pos.Line, d.Pos.Col, d.Message)
//	    }
//	    return errUserInput
//	}
//	use(program)
//
// # Различение ошибок
//
// Пользовательская ошибка в исходнике и внутренний сбой библиотеки НЕ смешаны:
//
//   - ошибка исходника (лексика/синтаксис/семантика) → err == nil, program == nil,
//     diags содержит записи уровня ir.SeverityError с дословным русским текстом
//     и позицией (строка/колонка, отсчёт с 1, в рунах);
//   - внутренний сбой (не прочитан файл, перехваченная паника) → err != nil.
//
// Инвариант: program != nil ⟺ среди diags нет записи уровня error.
//
// # Версионирование
//
// Модуль версионируется по semver. Изменение сигнатур Compile/CompileFile —
// MAJOR. Форма результата регулируется отдельно, через [ir.SchemaVersion];
// правила «что breaking, что аддитивно» — в документации пакета ir.
