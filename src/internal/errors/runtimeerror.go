package errors

import "fmt"

// ОшибкаВыполнения — ошибка стадии 4 (исполнение): деление на ноль, переполнение
// int64, индекс вне диапазона, лимит рекурсии, рантайм-ошибки стдлиб, функция-
// как-значение/не-функция, period-имя «не объявлено».
//
// Тот же дом-паттерн {Pos, Msg} + метод-значение Error(); позиция в РУНАХ; формат
// байт-в-байт совпадает с LexError/ParseError. Листовость: НЕ импортирует
// ast/value (Guardrail 14) — <тип> подставляет вызывающий eval через
// value.TypeName().
type ОшибкаВыполнения struct {
	Pos Position
	Msg string
}

// Error возвращает канонический двухстрочный вид (§8.1).
func (e ОшибкаВыполнения) Error() string {
	return fmt.Sprintf("Ошибка в строке %d, колонка %d:\n%s", e.Pos.Line, e.Pos.Col, e.Msg)
}
