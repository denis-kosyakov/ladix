package errors

import "fmt"

// Warning — предупреждение. Заголовок формата зарезервирован ради стабильности
// контракта диагностики (FR-004), но ЛЕКСЕР предупреждений НЕ порождает (A5):
// тип существует только для будущих слоёв (семантика).
type Warning struct {
	Pos Position
	Msg string
}

// Error возвращает канонический двухстрочный вид с заголовком предупреждения:
//
//	Предупреждение в строке N, колонка M:
//	<описание>
func (w Warning) Error() string {
	return fmt.Sprintf("Предупреждение в строке %d, колонка %d:\n%s", w.Pos.Line, w.Pos.Col, w.Msg)
}
