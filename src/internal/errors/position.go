package errors

// Position — позиция в исходном тексте.
//
// Отсчёт 1-based; колонка считается в РУНАХ (Unicode code points), не в байтах
// (конституция IV, SC-002) — язык кириллический. Тип общий: встраивается в
// токены лексера и в типы ошибок этого пакета.
//
// Инварианты для любого реального токена/ошибки: Line ≥ 1, Col ≥ 1.
type Position struct {
	Line int // номер строки, 1-based
	Col  int // номер колонки в рунах, 1-based
}
