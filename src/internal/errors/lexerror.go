package errors

import "fmt"

// LexError — лексическая ошибка: позиция первой руны проблемного места плюс
// русское описание БЕЗ заголовка (например "незакрытый строковый литерал").
//
// Тексты описаний берутся дословно из SPEC §13.4 / contracts/lexical-errors.md
// (конституция VIII, FR-024); переформулировать их запрещено. В штатных путях
// паника не используется (конституция III).
type LexError struct {
	Pos Position
	Msg string
}

// Error возвращает канонический двухстрочный вид (SPEC §13):
//
//	Ошибка в строке N, колонка M:
//	<описание>
//
// Значение реализует интерфейс error и разворачивается через errors.As (FR-003).
func (e LexError) Error() string {
	return fmt.Sprintf("Ошибка в строке %d, колонка %d:\n%s", e.Pos.Line, e.Pos.Col, e.Msg)
}
