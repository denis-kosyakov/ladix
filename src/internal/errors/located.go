package errors

// Расположенная — eval-ошибка, УЖЕ несущая позицию в исходном тексте (двухстрочный
// канон §13). Реализуется значимыми типами стадий 3/4: СемантическаяОшибка (Analyze),
// ОшибкаТипа и ОшибкаВыполнения (исполнение) — все с методом-ЗНАЧЕНИЕМ (важно для
// errors.As по значению, как Error()).
//
// Маркер нужен на границе eval↔engine (D-1): eval НЕ импортирует engine, поэтому
// «уже позиционирована?» проверяется ЭТИМ своим признаком, а не engine.StoreError.
// evalRunProcess пропускает Расположенную как есть (позиция тела/атрибута, §EN-9),
// а чужую не-позиционированную ошибку (StoreError движка) оборачивает позицией узла
// «запустить процесс» (§EN-8.A #8).
type Расположенная interface {
	error
	Позиция() Position
}
