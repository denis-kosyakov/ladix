// dt — короткий конструктор value.Дата для табличных тестов окон.
func dt(y, m, d int) value.Дата { return value.Дата{Year: y, Month: m, Day: d} }

// T021: окна по value.Период — таблица §SM-8.2 при D = 2026-05-31 (воскресенье)
// + краевой случай недели через границу месяца.
func TestPeriodWindow(t *testing.T) {
	cases := []struct {
		name           string
		period         string
		d              value.Дата
		wantStart, end value.Дата
	}{
		// D = 2026-05-31 — воскресенье (граница недели и месяца).
		{"ежедневно", "ежедневно", dt(2026, 5, 31), dt(2026, 5, 31), dt(2026, 5, 31)},
		{"еженедельно вс на границе", "еженедельно", dt(2026, 5, 31), dt(2026, 5, 25), dt(2026, 5, 31)},
		{"ежемесячно май", "ежемесячно", dt(2026, 5, 31), dt(2026, 5, 1), dt(2026, 5, 31)},
		{"ежеквартально Q2", "ежеквартально", dt(2026, 5, 31), dt(2026, 4, 1), dt(2026, 6, 30)},
		{"ежегодно", "ежегодно", dt(2026, 5, 31), dt(2026, 1, 1), dt(2026, 12, 31)},
		// Краевой: понедельник 2026-06-01 — неделя [06-01, 06-07] (не пересекает назад).
		{"еженедельно пн начало месяца", "еженедельно", dt(2026, 6, 1), dt(2026, 6, 1), dt(2026, 6, 7)},
		// Краевой: неделя пересекает границу месяца назад (вторник 2026-06-02 → пн 06-01).
		{"еженедельно вт", "еженедельно", dt(2026, 6, 2), dt(2026, 6, 1), dt(2026, 6, 7)},
		// Краевой: ежемесячно февраль 2024 (високосный) → 29 дней.
		{"ежемесячно фев високосный", "ежемесячно", dt(2024, 2, 10), dt(2024, 2, 1), dt(2024, 2, 29)},
		// Краевой: ежемесячно февраль 2026 (невисокосный) → 28 дней.
		{"ежемесячно фев невисокосный", "ежемесячно", dt(2026, 2, 10), dt(2026, 2, 1), dt(2026, 2, 28)},
		// Кварталы Q1/Q3/Q4.
		{"ежеквартально Q1", "ежеквартально", dt(2026, 2, 15), dt(2026, 1, 1), dt(2026, 3, 31)},
		{"ежеквартально Q3", "ежеквартально", dt(2026, 8, 15), dt(2026, 7, 1), dt(2026, 9, 30)},
		{"ежеквартально Q4", "ежеквартально", dt(2026, 11, 15), dt(2026, 10, 1), dt(2026, 12, 31)},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			start, end, ok := periodWindow(value.Период{Name: c.period}, c.d)
			if !ok {
				t.Fatalf("periodWindow(%s) вернул ok=false", c.period)
			}
			if start != c.wantStart {
				t.Errorf("начало = %+v, хотим %+v", start, c.wantStart)
			}
			if end != c.end {
				t.Errorf("конец = %+v, хотим %+v", end, c.end)
			}
			// Граница включительна: начало ≤ конец.
			if cmp, ok := value.Compare(start, end); !ok || cmp > 0 {
				t.Errorf("начало %+v должно быть ≤ конец %+v (cmp=%d ok=%v)", start, end, cmp, ok)
			}
		})
	}
}

