// Инварианты выражений SC-004: значение (репрезентация §7) и КАНОНИЧЕСКИЙ тип
// (через value.TypeName, белым ящиком — встроенная тип() недостижима из
// исходника, лексер резервирует «тип»).
func TestExprValueAndType(t *testing.T) {
	tests := []struct {
		name     string
		expr     string
		wantRepr string
		wantType string
	}{
		{"приоритеты 2+3*4", "2 + 3 * 4", "14", "Целое"},
		{"скобки (2+3)*4", "(2 + 3) * 4", "20", "Целое"},
		{"деление всегда Дробное 7/2", "7 / 2", "3.5", "Дробное"},
		{"деление 6/2 = 3.0", "6 / 2", "3.0", "Дробное"},
		{"целочисленное 7//2", "7 // 2", "3", "Целое"},
		{"остаток 7%2", "7 % 2", "1", "Целое"},
		{"дробный остаток fmod", "7.5 % 2.0", "1.5", "Дробное"},
		{"промоушен 1+2.0", "1 + 2.0", "3.0", "Дробное"},
		{"унарный минус", "-5 * -5", "25", "Целое"},
		{"конкатенация строк", "\"а\" + \"б\"", "аб", "Строка"},
		{"равенство численно 1==1.0", "1 == 1.0", "истина", "Булево"},
		{"равенство списков", "[1, 2] == [1, 2]", "истина", "Булево"},
		{"сравнение строк", "\"а\" < \"б\"", "истина", "Булево"},
		{"логика и", "2 < 3 и 3 < 4", "истина", "Булево"},
		{"не Булево", "не ложь", "истина", "Булево"},
		{"индекс списка", "[10, 20, 30][1]", "20", "Целое"},
		{"индекс строки в рунах", "\"привет\"[0]", "п", "Строка"},
		{"список литерал", "[1, \"две\", истина]", "[1, две, истина]", "Список"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			v := evalExpr1(t, tt.expr)
			if got := value.String(v); got != tt.wantRepr {
				t.Errorf("репрезентация = %q, хотим %q", got, tt.wantRepr)
			}
			if got := v.TypeName(); got != tt.wantType {
				t.Errorf("тип = %q, хотим %q", got, tt.wantType)
			}
		})
	}
}

// Короткое замыкание: правый операнд не вычисляется (1/0 не падает).
func TestShortCircuit(t *testing.T) {
	tests := []struct {
		name, src, want string
	}{
		{"ложь и не вычисляет правый", "печать(ложь и (1 / 0 == 0))", "ложь\n"},
		{"истина или не вычисляет правый", "печать(истина или (1 / 0 == 0))", "истина\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			out, err := run(t, tt.src)
			if err != nil {
				t.Fatalf("неожиданная ошибка (правый операнд вычислен?): %v", err)
			}
			if out != tt.want {
				t.Errorf("= %q, хотим %q", out, tt.want)
			}
		})
	}
}

// Переполнение int64 в + — явная ошибка, не wrap-around.
func TestIntOverflow(t *testing.T) {
	out, err := run(t, "печать(9223372036854775807 + 1)")
	if err == nil {
		t.Fatalf("ожидалось переполнение, получено %q", out)
	}
	_, _, msg := evalErr(t, err)
	if msg != "переполнение целого числа" {
		t.Errorf("msg = %q", msg)
	}
	if !isRuntime(err) {
		t.Errorf("категория не ОшибкаВыполнения")
	}
}
