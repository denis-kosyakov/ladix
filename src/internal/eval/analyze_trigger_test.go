// T025 (007a, §TR-4, diagnostics.md §TR-7.A/.B/.C/.D, SC-005/SC-007) — НЕГАТИВЫ
// семантической валидации триггеров: payload БАЙТ-В-БАЙТ из contracts/diagnostics.md
// + точная позиция (строка, колонка в рунах) узла-нарушителя; все — категория
// СемантическаяОшибка (evalErr/isSem). Новые 4 диагностики (TR-VAL-CTX/TR-EVT-CTX/
// TR-MET-UNDECL/TR-MET-NOTMETRIC) + переиспользуемые семейства (§TR-7.C действия-
// шага, §TR-7.D арность/вид запуска и `вернуть` вне функции).
//
// Преамбулы (валидные декларации) — как в TestAnalyzeTriggerOK.
func TestAnalyzeTriggerNegatives(t *testing.T) {
	const metric = "источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s\n    агрегат: сумма(x)\n"
	const fn = "функция f():\n    вернуть 1\n"
	const proc1 = "процесс P(x):\n    шаг A:\n        печать(1)\n"

	tests := []struct {
		name      string
		src       string
		want      string
		line, col int
	}{
		// --- §TR-7.A контекст-гард предопределённых имён ---
		{
			// TR-VAL-CTX: `значение` в теле событие-триггера (inMetricTrigger=false).
			name: "TR-VAL-CTX значение в теле события",
			src:  "когда событие e:\n    печать(значение)\n",
			want: "выражение 'значение' допустимо только в теле триггера метрики",
			line: 2, col: 12, // токен 'значение' (аргумент печать)
		},
		{
			// TR-VAL-CTX: `значение` в теле расписания (оба флага false).
			name: "TR-VAL-CTX значение в теле расписания",
			src:  "когда расписание каждые 5мин:\n    печать(значение)\n",
			want: "выражение 'значение' допустимо только в теле триггера метрики",
			line: 2, col: 12,
		},
		{
			// TR-EVT-CTX: `событие` в теле метрика-триггера (inEventTrigger=false).
			name: "TR-EVT-CTX событие в теле метрики",
			src:  metric + "когда метрика m > 1:\n    печать(событие)\n",
			want: "выражение 'событие' допустимо только в теле триггера события",
			line: 7, col: 12, // токен 'событие' (аргумент печать; преамбула 5 строк)
		},
		{
			// TR-EVT-CTX: `событие.поле` в теле расписания (оба флага false) — гард
			// доходит до EventExpr через FieldExpr.Target.
			name: "TR-EVT-CTX событие.поле в теле расписания",
			src:  "когда расписание в \"08:30\":\n    печать(событие.клиент)\n",
			want: "выражение 'событие' допустимо только в теле триггера события",
			line: 2, col: 12,
		},
		// --- §TR-7.B условие метрика-триггера ---
		{
			// TR-MET-UNDECL: имя в условии не зарегистрировано ни одним видом.
			name: "TR-MET-UNDECL необъявленная метрика",
			src:  "когда метрика нету > 1:\n    печать(1)\n",
			want: "метрика 'нету' не объявлена",
			line: 1, col: 15, // токен имени метрики после 'когда метрика '
		},
		{
			// TR-MET-NOTMETRIC: имя занято процессом, не метрикой.
			name: "TR-MET-NOTMETRIC имя — процесс",
			src:  "процесс P:\n    шаг A:\n        печать(1)\nкогда метрика P > 1:\n    печать(1)\n",
			want: "'P' — не метрика",
			line: 4, col: 15, // токен 'P' в условии (преамбула 3 строки)
		},
		{
			// TR-MET-NOTMETRIC: имя занято функцией, не метрикой.
			name: "TR-MET-NOTMETRIC имя — функция",
			src:  fn + "когда метрика f > 1:\n    печать(1)\n",
			want: "'f' — не метрика",
			line: 3, col: 15, // токен 'f' (преамбула fn 2 строки)
		},
		{
			// TR-MET-NOTMETRIC: имя занято источником, не метрикой.
			name: "TR-MET-NOTMETRIC имя — источник",
			src:  "источник s:\n    файл: \"d.json\"\nкогда метрика s > 1:\n    печать(1)\n",
			want: "'s' — не метрика",
			line: 3, col: 15, // токен 's' (преамбула источника 2 строки)
		},
		// --- §TR-7.C действие-шага в теле триггера (переиспользование §PM-6.B) ---
		{
			// TR-ACTION-CTX: `присвоить` в теле триггера (inStep=false).
			name: "TR-ACTION-CTX присвоить в теле метрики",
			src:  metric + "когда метрика m > 1:\n    присвоить x = 5\n",
			want: "действие 'присвоить' допустимо только в шаге процесса",
			line: 7, col: 5, // токен 'присвоить' (преамбула 5 строк)
		},
		{
			// TR-ACTION-CTX: `вызвать` в теле события.
			name: "TR-ACTION-CTX вызвать в теле события",
			src:  "когда событие e:\n    вызвать f(1)\n",
			want: "действие 'вызвать' допустимо только в шаге процесса",
			line: 2, col: 5,
		},
		{
			// TR-ACTION-CTX: `уведомить` в теле расписания.
			name: "TR-ACTION-CTX уведомить в теле расписания",
			src:  "когда расписание каждые 1дн:\n    уведомить g(a)\n",
			want: "действие 'уведомить' допустимо только в шаге процесса",
			line: 2, col: 5,
		},
		// --- §TR-7.D запуск процесса из тела триггера (переиспользование §PM-6.C) ---
		{
			// TR-PROC-ARITY: неверная арность `запустить процесс` в теле.
			name: "TR-PROC-ARITY неверная арность запуска",
			src:  metric + proc1 + "когда метрика m > 1:\n    запустить процесс P(1, 2)\n",
			want: "'P' принимает 1 аргументов, передано 2",
			line: 10, col: 5, // токен 'запустить' (преамбула metric 5 + proc1 3 + заголовок 1)
		},
		{
			// неверный ВИД: имя — функция, не процесс (через `запустить процесс`).
			name: "TR-PROC-ISFUNC запуск функции как процесса",
			src:  fn + "когда событие e:\n    запустить процесс f()\n",
			want: "'f' — функция, не процесс",
			line: 4, col: 5, // токен 'запустить' (преамбула fn 2 строки + заголовок триггера)
		},
		{
			// неверный ВИД: имя не объявлено как процесс.
			name: "TR-PROC-UNDECL запуск необъявленного процесса",
			src:  "когда событие e:\n    запустить процесс Нет()\n",
			want: "процесс 'Нет' не объявлен",
			line: 2, col: 5, // токен 'запустить'
		},
		// --- §TR-7.D `вернуть` вне функции в теле триггера (eval §7.3) ---
		{
			// TR-RETURN-CTX: голый `вернуть` в теле триггера (не функция, не шаг →
			// только базовый текст, без суффикса «; в шаге процесса …»).
			name: "TR-RETURN-CTX вернуть в теле триггера",
			src:  "когда событие e:\n    вернуть 1\n",
			want: "'вернуть' допустимо только внутри функции",
			line: 2, col: 5, // токен 'вернуть'
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := analyzeSrc(t, tt.src)
			if err == nil {
				t.Fatalf("ожидалась семантическая ошибка %q, получено nil", tt.want)
			}
			if !isSem(err) {
				t.Errorf("категория не СемантическаяОшибка: %T", err)
			}
			line, col, msg := evalErr(t, err)
			if msg != tt.want {
				t.Errorf("msg = %q, хотим %q", msg, tt.want)
			}
			if line != tt.line || col != tt.col {
				t.Errorf("позиция = (%d,%d), хотим (%d,%d)", line, col, tt.line, tt.col)
			}
		})
	}
}

// Шаг 1d (007a, §TR-4) — позитивы семантической валидации триггеров: валидные
// триггеры всех трёх форм проходят чисто. Метрика резолвится против i.metrics;
// `значение` в теле метрика-триггера и `событие` в теле событие-триггера
// допустимы (контекст-гард §TR-7.A, оба флага); `запустить процесс` с верной
// арностью в теле — чисто (переиспользование checkRunProcess §PM-6.C); порог —
// обычное выражение (резолв/арность). Тело тождественно top-level по набору
// разрешённых конструкций (императивное ядро минус действия-шага, §TR-5).
//
// Преамбулы (валидные декларации источника/метрики/процесса) конструируются как
// в analyze_decl_test.go.
func TestAnalyzeTriggerOK(t *testing.T) {
	const metric = "источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s\n    агрегат: сумма(x)\n"
	const proc1 = "процесс P(x):\n    шаг A:\n        печать(1)\n"

	tests := []struct {
		name string
		src  string
	}{
		{
			// метрика-триггер: метрика резолвится, порог — литерал, тело печатает.
			"метрика-триггер чистый",
			metric + "когда метрика m > 100:\n    печать(1)",
		},
		{
			// `значение` в теле метрика-триггера — OK (inMetricTrigger=true).
			"значение в теле метрики",
			metric + "когда метрика m > 100:\n    печать(значение)",
		},
		{
			// `значение` глубоко в выражении тела метрики — гард доходит рекурсивно.
			"значение в выражении тела метрики",
			metric + "когда метрика m >= 1:\n    пусть y = значение + 1\n    печать(y)",
		},
		{
			// событие-триггер: имя события НЕ резолвится (реестра нет — 007b),
			// тело валидируется полностью.
			"событие-триггер чистый",
			"когда событие заказ_создан:\n    печать(1)",
		},
		{
			// `событие` в теле событие-триггера — OK (inEventTrigger=true).
			"событие в теле события",
			"когда событие заказ_создан:\n    печать(событие)",
		},
		{
			// `событие.поле` — FieldExpr над EventExpr, тот же контекст-гард.
			"событие.поле в теле события",
			"когда событие заказ_создан:\n    печать(событие.клиент)",
		},
		{
			// расписание `каждые`: содержимое не анализируется, тело чисто.
			"расписание каждые чистый",
			"когда расписание каждые 5мин:\n    печать(1)",
		},
		{
			// расписание `в "ЧЧ:ММ"`: формат строки НЕ валидируется в 007a (→ 007b).
			"расписание в время чистый",
			"когда расписание в \"08:30\":\n    печать(1)",
		},
		{
			// `запустить процесс` с верной арностью в теле триггера — чисто
			// (переиспользование checkRunProcess, реестр процессов готов с Шага 1).
			"запустить процесс верная арность в теле",
			metric + proc1 + "когда метрика m > 100:\n    пусть id = запустить процесс P(\"Петров\")\n    печать(id)",
		},
		{
			// `значение` как аргумент запускаемого процесса в теле метрики — OK.
			"значение в аргументе запуска процесса",
			metric + proc1 + "когда метрика m > 100:\n    запустить процесс P(значение)",
		},
		{
			// императивное ядро в теле: пусть/если/для/пока — чисто (тождество top-level).
			"императивные конструкции в теле триггера",
			metric + "когда метрика m > 100:\n    пусть n = значение\n    если n > 0:\n        для k в [1, 2]:\n            печать(k)\n    иначе:\n        печать(0)",
		},
		{
			// несколько триггеров подряд — каждый регистрируется и валидируется.
			"несколько триггеров",
			metric + "когда метрика m > 1:\n    печать(1)\nкогда событие e:\n    печать(2)\nкогда расписание каждые 1час:\n    печать(3)",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if err := analyzeSrc(t, tt.src); err != nil {
				t.Errorf("семантика триггера должна быть чистой: %v", err)
			}
		})
	}
}

// T013 (016 B4a, §AU-6.1.3): семпроход эскалация-триггера. Позитив — процесс+шаг
// объявлены, тело со свободным `факт` (резолвится в рантайме против инжекта
// InstanceVariables, B4b) → analyze OK. Негативы: (а) неизв. процесс →
// `процесс '<имя>' не объявлен` (exact+поз. Process); (б) известный процесс, неизв.
// шаг → `шаг '<шаг>' не найден в процессе '<процесс>'` (exact+поз. Step);
// (в) `значение`/`событие` в теле → наследуемый контекст-гард (оба флага false,
// как расписание, D-AU-6). Семейство analyze_trigger_test (§AU-10.B) — НЕ инкрементит
// errors_golden eval=28.
func TestDeadlineTriggerSemantics(t *testing.T) {
	const proc = "процесс согласование(заявка):\n    шаг проверка:\n        печать(заявка)\n"

	t.Run("позитив процесс+шаг+свободный факт", func(t *testing.T) {
		// Тело — императивное ядро со свободным `факт` (резолв в рантайме против
		// инжекта InstanceVariables, B4b). `уведомить`/`вызвать` как реальные
		// действия в теле — граница B2 (наследуемый §TR-7.C запрет здесь не
		// смягчается); B4a берёт печать как валидное императивное ядро.
		src := proc + "когда задача просрочена в согласование.проверка:\n    печать(\"[уведомление] руководитель:\", факт)\n"
		if err := analyzeSrc(t, src); err != nil {
			t.Errorf("эскалация-триггер должен пройти семпроход чисто: %v", err)
		}
	})

	negatives := []struct {
		name      string
		src       string
		want      string
		line, col int
	}{
		{
			name: "неизвестный процесс",
			src:  "когда задача просрочена в НетП.S:\n    печать(1)\n",
			want: "процесс 'НетП' не объявлен",
			line: 1, col: 27, // токен имени процесса после 'когда задача просрочена в '
		},
		{
			name: "известный процесс, неизвестный шаг",
			src:  proc + "когда задача просрочена в согласование.нетшага:\n    печать(1)\n",
			want: "шаг 'нетшага' не найден в процессе 'согласование'",
			line: 4, col: 40, // токен имени шага после 'когда задача просрочена в согласование.'
		},
		{
			name: "значение в теле эскалации",
			src:  proc + "когда задача просрочена в согласование.проверка:\n    печать(значение)\n",
			want: "выражение 'значение' допустимо только в теле триггера метрики",
			line: 5, col: 12,
		},
		{
			name: "событие в теле эскалации",
			src:  proc + "когда задача просрочена в согласование.проверка:\n    печать(событие)\n",
			want: "выражение 'событие' допустимо только в теле триггера события",
			line: 5, col: 12,
		},
	}
	for _, tt := range negatives {
		t.Run(tt.name, func(t *testing.T) {
			err := analyzeSrc(t, tt.src)
			if err == nil {
				t.Fatalf("ожидалась семантическая ошибка %q, получено nil", tt.want)
			}
			if !isSem(err) {
				t.Errorf("категория не СемантическаяОшибка: %T", err)
			}
			line, col, msg := evalErr(t, err)
			if msg != tt.want {
				t.Errorf("msg = %q, хотим %q", msg, tt.want)
			}
			if line != tt.line || col != tt.col {
				t.Errorf("позиция = (%d,%d), хотим (%d,%d)", line, col, tt.line, tt.col)
			}
		})
	}
}
