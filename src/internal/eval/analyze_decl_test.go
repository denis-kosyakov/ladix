package eval

import "testing"

// Шаг 1 — объединённый упорядоченный проход: повтор имени в общем глобальном
// пространстве (функция/источник/метрика). Различение текста: функция↔функция —
// старый текст (R5, регресс 003); любая коллизия с участием источника/метрики —
// §SM-9.A «'<имя>' уже объявлено в строке N».
func TestAnalyzeDeclRedeclare(t *testing.T) {
	tests := []struct {
		name     string
		src      string
		wantMsg  string
		wantLine int
		wantCol  int
	}{
		{
			// функция↔функция — старый текст (регресс 003).
			"повтор функция-функция (старый текст)",
			"функция f():\n    вернуть 1\nфункция f():\n    вернуть 2",
			"функция 'f' уже объявлена в строке 1",
			3, 9,
		},
		{
			// источник↔метрика — §SM-9.A.
			"источник затем метрика (тот же name)",
			"источник продажи:\n    файл: \"d.json\"\nметрика продажи:\n    источник: продажи\n    агрегат: сумма(x)",
			"'продажи' уже объявлено в строке 1",
			3, 9,
		},
		{
			// функция↔источник — §SM-9.A.
			"функция затем источник (тот же name)",
			"функция отчёт():\n    вернуть 1\nисточник отчёт:\n    файл: \"d.json\"",
			"'отчёт' уже объявлено в строке 1",
			3, 10,
		},
		{
			// метрика↔метрика — §SM-9.A (участие метрики).
			"повтор метрики",
			"источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s\n    агрегат: сумма(x)\nметрика m:\n    источник: s\n    агрегат: сумма(y)",
			"'m' уже объявлено в строке 3",
			6, 9,
		},
		{
			// источник↔функция (источник раньше) — §SM-9.A. Второй декл — функция
			// (ключевое слово «функция» 7 рун), имя начинается с колонки 9.
			"источник затем функция (тот же name)",
			"источник data:\n    файл: \"d.json\"\nфункция data():\n    вернуть 1",
			"'data' уже объявлено в строке 1",
			3, 9,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := analyzeSrc(t, tt.src)
			if err == nil {
				t.Fatalf("ожидалась ошибка семпрохода")
			}
			line, col, msg := evalErr(t, err)
			if msg != tt.wantMsg {
				t.Errorf("msg = %q, хотим %q", msg, tt.wantMsg)
			}
			if line != tt.wantLine || col != tt.wantCol {
				t.Errorf("позиция = %d:%d, хотим %d:%d", line, col, tt.wantLine, tt.wantCol)
			}
			if !isSem(err) {
				t.Errorf("категория не СемантическаяОшибка")
			}
		})
	}
}

// Шаг 1b — статическая валидация метрик: обязательность источник/агрегат, связка
// период↔по_дате, резолв источника. Тексты §SM-9.A дословно; позиция проверяется.
func TestAnalyzeMetricStaticValidation(t *testing.T) {
	tests := []struct {
		name     string
		src      string
		wantMsg  string
		wantLine int
		wantCol  int
	}{
		{
			// отсутствует обязательный источник → поз. токена метрика.
			"нет источника",
			"метрика m:\n    агрегат: сумма(x)",
			"метрика 'm': отсутствует обязательный атрибут 'источник'",
			1, 1,
		},
		{
			// отсутствует обязательный агрегат → поз. токена метрика.
			"нет агрегата",
			"источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s",
			"метрика 'm': отсутствует обязательный атрибут 'агрегат'",
			3, 1,
		},
		{
			// период есть, по_дате нет → поз. период.
			"период без по_дате",
			"источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s\n    агрегат: сумма(x)\n    период: ежемесячно",
			"метрика 'm': 'период' требует 'по_дате'",
			6, 5,
		},
		{
			// по_дате есть, период нет → поз. по_дате.
			"по_дате без период",
			"источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s\n    агрегат: сумма(x)\n    по_дате: дата_заказа",
			"метрика 'm': 'по_дате' без 'период' не имеет смысла",
			6, 5,
		},
		{
			// источник не объявлен → поз. источник:.
			"неизвестный источник",
			"метрика m:\n    источник: нету\n    агрегат: сумма(x)",
			"метрика 'm': источник 'нету' не объявлен",
			2, 5,
		},
		{
			// имя занято функцией → «не источник», поз. источник:.
			"источник занят функцией",
			"функция продажи():\n    вернуть 1\nметрика m:\n    источник: продажи\n    агрегат: сумма(x)",
			"метрика 'm': 'продажи' — не источник",
			4, 5,
		},
		{
			// имя занято метрикой → «не источник», поз. источник:.
			"источник занят метрикой",
			"источник s:\n    файл: \"d.json\"\nметрика база:\n    источник: s\n    агрегат: сумма(x)\nметрика m:\n    источник: база\n    агрегат: сумма(y)",
			"метрика 'm': 'база' — не источник",
			7, 5,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := analyzeSrc(t, tt.src)
			if err == nil {
				t.Fatalf("ожидалась ошибка семпрохода")
			}
			line, col, msg := evalErr(t, err)
			if msg != tt.wantMsg {
				t.Errorf("msg = %q, хотим %q", msg, tt.wantMsg)
			}
			if line != tt.wantLine || col != tt.wantCol {
				t.Errorf("позиция = %d:%d, хотим %d:%d", line, col, tt.wantLine, tt.wantCol)
			}
			if !isSem(err) {
				t.Errorf("категория не СемантическаяОшибка")
			}
		})
	}
}

// Корректная метрика без периода (источник+агрегат) — без ошибок семпрохода.
func TestAnalyzeMetricMinimalOK(t *testing.T) {
	src := "источник s:\n    файл: \"d.json\"\nметрика m:\n    источник: s\n    агрегат: сумма(x)"
	if err := analyzeSrc(t, src); err != nil {
		t.Errorf("минимальная метрика не должна давать ошибку: %v", err)
	}
}

