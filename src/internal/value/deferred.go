package value

// Типы дата-подсистемы: стабильная поверхность eval↔store (контракт C-1).
// Длительность теперь КОНСТРУИРУЕТСЯ (006/D-7: литерал длительности → evalDurationLit
// → value.Длительность{Amount, Unit}; равенство/порядок — D-17). Дата конструируется
// с 004 (§SM-6: дата()/сегодня()). Период — предопределённые константы (§SM-5).
// TypeName() даёт каноническое имя для подстановки <тип> в сообщениях (§8.3).

// Дата — календарная дата без времени (год-месяц-день).
type Дата struct {
	Year  int
	Month int
	Day   int
}

func (Дата) TypeName() string { return "Дата" }

// Длительность — величина и единица (сек/мин/час/дн/нед/мес); мес не сводится
// к секундам без даты-якоря.
type Длительность struct {
	Amount int64
	Unit   string
}

func (Длительность) TypeName() string { return "Длительность" }

// Период — период метрики (§MW-3). v1: календарная константа (ежедневно…ежегодно).
// 011-A2 расширяет АДДИТИВНО (пакет value остаётся листовым, без новых импортов):
//   - скользящее окно «последние N <ед>» → Name="последние", Amount=N, Unit=ед, Offset=0;
//   - «последний завершённый» «прошлый <noun>» → Name=<базовый адверб>, Offset=-1.
//
// 5 календарных констант сохраняют нулевые Amount/Unit/Offset → обр. совместимость
// (регистрация в interpreter.go не меняется, codec round-trip по Name корректен).
type Период struct {
	Name   string // "ежедневно".."ежегодно" (календарный) | "последние" (скользящий)
	Amount int64  // скользящий: N; иначе 0
	Unit   string // скользящий: "дн"/"нед"/"мес"; иначе ""
	Offset int    // «последний завершённый»: -1 к календарному Name; иначе 0
}

func (Период) TypeName() string { return "Период" }
