package value

// Deferred-типы дата-подсистемы: ОПРЕДЕЛЕНЫ как стабильная поверхность
// eval↔store, но в 003 НЕ конструируются (ворота закрыты, §1.2). Нужны только
// чтобы TypeName() давал каноническое имя для подстановки <тип> в сообщениях
// (реестр §8.3 перечисляет Дата/Длительность/Период среди возможных <тип>).
// Поля заданы по контракту C-1, но ни один путь кода 003 их не заполняет.

// Дата — календарная дата без времени (год-месяц-день).
type Дата struct {
	Year  int
	Month int
	Day   int
}

func (Дата) TypeName() string { return "Дата" }

// Длительность — величина и единица (сек/мин/час/дн/нед/мес); мес не сводится
// к секундам без даты-якоря.
type Длительность struct {
	Amount int64
	Unit   string
}

func (Длительность) TypeName() string { return "Длительность" }

// Период — константа периодичности (ежедневно…ежегодно); в 003 не предопределена.
type Период struct {
	Name string
}

func (Период) TypeName() string { return "Период" }
