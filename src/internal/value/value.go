package value

// Value — рантайм-значение Ladix. Реализуется РОВНО 10 конкретными типами
// (sum-type на Go: интерфейс-тег + конкретные структуры). Интерпретатор
// различает варианты через type switch.
//
// Единственный метод TypeName даёт каноническое имя типа («Целое», «Дробное»,
// …) — один источник истины и для встроенной тип(x), и для подстановки <тип>
// в сообщениях об ошибках, чтобы они не расходились.
type Value interface {
	TypeName() string
}
