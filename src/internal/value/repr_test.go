package value

import "testing"

// String — единое представление §7 (FR-030). Ключевой инвариант: Дробное,
// «выглядящее целым», печатается с принудительной .0 (2175 → 2175.0), что
// требуют golden-примеры; строки — без кавычек, в т.ч. внутри Список.
func TestStringRepr(t *testing.T) {
	tests := []struct {
		name string
		v    Value
		want string
	}{
		{"целое", Целое{V: 42}, "42"},
		{"целое отрицательное", Целое{V: -5}, "-5"},
		{"дробное .0 принудительно", Дробное{V: 2175}, "2175.0"},
		{"дробное 6/2 = 3.0", Дробное{V: 3}, "3.0"},
		{"дробное 3.14", Дробное{V: 3.14}, "3.14"},
		{"дробное 3.4", Дробное{V: 3.4}, "3.4"},
		{"дробное sci", Дробное{V: 1e20}, "1e+20"},
		{"строка без кавычек", Строка{V: "привет"}, "привет"},
		{"булево истина", Булево{V: true}, "истина"},
		{"булево ложь", Булево{V: false}, "ложь"},
		{"пусто", None, "пусто"},
		{
			"список со строкой без кавычек",
			NewList([]Value{Целое{V: 1}, Строка{V: "две"}, Булево{V: true}}),
			"[1, две, истина]",
		},
		{"пустой список", NewList(nil), "[]"},
		{
			"вложенный список",
			NewList([]Value{NewList([]Value{Целое{V: 250}, Целое{V: 400}})}),
			"[[250, 400]]",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := String(tt.v); got != tt.want {
				t.Errorf("String(%v) = %q, хотим %q", tt.v, got, tt.want)
			}
		})
	}
}
