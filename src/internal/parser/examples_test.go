package parser

import "testing"

// T048 (SC-001): сквозная проверка набора примеров.
//
// Набор parse-clean обязан давать НОЛЬ синтаксических ошибок: императивное ядро
// (подмножество B) + онбординг.ladix (процессы парсятся с 005, §PM-3) +
// выручка.ladix (триггер `когда` парсится с 007a, шов A; §TR-10.5 п.5).

func TestExamplesParseCleanSet(t *testing.T) {
	clean := []string{
		"hello.ladix", "арифметика.ladix",
		"условие.ladix", "цикл.ladix",
		"функция.ladix", "факториал.ladix",
		"ошибка.ladix",         // синтаксически валиден; дефект (деление на ноль) — рантайм
		"онбординг.ladix",      // процессы парсятся с 005 (§PM-3); рантайм-граница — 'запустить процесс' (§PM-5)
		"выручка.ladix",        // триггер `когда метрика … < …:` парсится с 007a (шов A, §TR-1)
		"событие.ladix",        // триггер `когда событие <Ident>:` парсится с 007a (US3 класс 1)
		"расписание.ladix",     // триггеры `когда расписание каждые Nдн / в "ЧЧ:ММ":` парсятся с 007a (US3 класс 2)
		"метрики.ladix",        // мультиисточник/мультиметрика: 2 источника + 3 метрики + триггеры (US3 класс 3)
		"процесс.ladix",        // полный цикл процесса: 2 человеческих шага через «после» (US3 класс 4)
		"ошибка_тип.ladix",     // парсится чисто; дефект (Целое + Строка) — рантайм типов (US3 негатив)
		"ошибка_процесс.ladix", // парсится чисто; дефект ('запустить процесс' необъявленного) — рантайм (US3 негатив)
		// 010-A1 коннекторы источника: три позитивные демо (тип:/поля:) парсятся чисто.
		"источник_csv.ladix",        // тип: csv + схема поля: (010-A1, US1)
		"источник_ndjson.ladix",     // тип: ndjson + схема поля: (010-A1, US3)
		"источник_json_схема.ladix", // тип: json + поля: поверх JSON-массива (010-A1, US2)
		"ошибочная.ladix",           // парсится чисто; дефект (Дробное→Целое коэрсия) — рантайм загрузки (010-A1, как ошибка_тип)
		// 011-A2 оконные метрики: три позитивные демо (период: последние N <ед> / прошлый <noun>) парсятся чисто.
		"окно_скользящее.ladix",  // период: последние 30дн + по_дате (011-A2, US1)
		"окно_завершённое.ladix", // период: прошлый месяц + по_дате (011-A2, US2)
		"выручка_30д.ladix",      // DoD-срез: последние 30дн над data/orders.csv (011-A2, US1)
		// негативы окно_единица/окно_размер/окно_noun НЕ включены: они ОБЯЗАНЫ падать в Analyze (негатив-stderr в golden_test).
		// ошибка_синтаксис.ladix НЕ включён намеренно: он ОБЯЗАН падать на парсинге (негатив-stderr в golden_test).
	}
	for _, name := range clean {
		t.Run(name, func(t *testing.T) {
			prog, el, lexErrs := parseExampleFile(t, name)
			if !lexErrs.Empty() {
				t.Fatalf("%s: лексические ошибки: %v", name, lexErrs.Error())
			}
			if !el.Empty() {
				t.Fatalf("%s: синтаксические ошибки: %v", name, el.Error())
			}
			if len(prog.Items) == 0 {
				t.Errorf("%s: пустой Program.Items", name)
			}
		})
	}
}
